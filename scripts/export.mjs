// Writes the TV app's copy of the content: sized photos and the data file.
// Usage: node export.mjs   (from scripts/, or `npm --prefix scripts run export`)
// Outputs are committed; each app builds only from its own folder.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const SIZES = {
  backdrop: { width: 1920, height: 1080 },
  tile: { width: 480, height: 270 },
};
const JPEG = { quality: 80, mozjpeg: true, chromaSubsampling: '4:2:0' };

async function writeJpeg(src, dest, { width, height }) {
  // `attention` keeps the busiest part of the photo in a 16:9 crop; metadata is
  // stripped by default, so the bytes depend only on the master.
  const buf = await sharp(src).resize(width, height, { fit: 'cover', position: sharp.strategy.attention }).jpeg(JPEG).toBuffer();
  writeFileSync(dest, buf);
}

function imagesModule(slugs) {
  const map = (kind) => slugs.map((s) => `  '${s}': require('../../assets/destinations/${s}-${kind}.jpg'),`).join('\n');
  return `// Generated by scripts/export.mjs. Do not edit.
import type { ImageSourcePropType } from 'react-native';

export const backdrops: Record<string, ImageSourcePropType> = {
${map('backdrop')}
};

export const tiles: Record<string, ImageSourcePropType> = {
${map('tile')}
};
`;
}

export async function exportTv({ root }) {
  const data = JSON.parse(readFileSync(join(root, 'content', 'destinations.json'), 'utf8'));
  const assetDir = join(root, 'tv', 'assets', 'destinations');
  const dataDir = join(root, 'tv', 'src', 'data');
  mkdirSync(assetDir, { recursive: true });
  mkdirSync(dataDir, { recursive: true });
  const files = [];
  const slugs = data.destinations.map((d) => d.slug);
  for (const slug of slugs) {
    const master = join(root, 'content', 'photos', `${slug}.jpg`);
    for (const [kind, size] of Object.entries(SIZES)) {
      const dest = join(assetDir, `${slug}-${kind}.jpg`);
      await writeJpeg(master, dest, size);
      files.push(dest);
    }
  }
  const json = join(dataDir, 'destinations.json');
  writeFileSync(json, JSON.stringify(data, null, 2) + '\n');
  const images = join(dataDir, 'images.ts');
  writeFileSync(images, imagesModule(slugs));
  files.push(json, images);
  return { files };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const { files } = await exportTv({ root });
  console.log(`wrote ${files.length} files`);
}
